"""Testa funções que só LEEM estado (sem mexer em mouse/teclado/janelas)."""
import uiautomation as auto, traceback, time, os
def t(label, fn):
    try:
        r = fn(); s = repr(r)
        print(f"[OK ] {label} -> {s[:230]}")
        return r
    except Exception as e:
        print(f"[ERR] {label} -> {type(e).__name__}: {e}")
t("GetScreenSize", auto.GetScreenSize)
t("GetVirtualScreenSize", auto.GetVirtualScreenSize)
t("GetMonitorsRect", auto.GetMonitorsRect)
t("GetCursorPos", auto.GetCursorPos)
t("GetPhysicalCursorPos", auto.GetPhysicalCursorPos)
t("GetDoubleClickTime", auto.GetDoubleClickTime)
t("IsUserAnAdmin", auto.IsUserAnAdmin)
t("IsDesktopLocked", auto.IsDesktopLocked)
t("DwmIsCompositionEnabled", auto.DwmIsCompositionEnabled)
t("GetForegroundWindow", auto.GetForegroundWindow)
t("GetConsoleTitle", auto.GetConsoleTitle)
t("GetConsoleOriginalTitle", auto.GetConsoleOriginalTitle)
t("IsProcess64Bit(self)", lambda: auto.IsProcess64Bit(os.getpid()))
t("IsKeyPressed(VK_SHIFT)", lambda: auto.IsKeyPressed(auto.Keys.VK_SHIFT))
t("GetClipboardFormats", auto.GetClipboardFormats)
t("GetRootControl", auto.GetRootControl)
root = auto.GetRootControl()
t("root.ControlTypeName", lambda: root.ControlTypeName)
t("root.GetChildren count", lambda: len(root.GetChildren()))
t("root.BoundingRectangle", lambda: root.BoundingRectangle)
t("GetFocusedControl", auto.GetFocusedControl)
t("GetForegroundControl", auto.GetForegroundControl)
t("GetConsoleWindow", auto.GetConsoleWindow)
t("ControlFromCursor", auto.ControlFromCursor)
t("ControlFromCursor2", auto.ControlFromCursor2)
x,y = auto.GetCursorPos()
t("WindowFromPoint", lambda: auto.WindowFromPoint(x,y))
t("GetPixelColor(0,0)", lambda: auto.GetPixelColor(x,y))
procs = t("GetProcesses(detailed)", lambda: auto.GetProcesses(True))
if procs:
    print("   primeiro processo:", procs[0], "| attrs:", [a for a in dir(procs[0]) if not a.startswith('_')])
t("GetProcesses(False)[0]", lambda: auto.GetProcesses(False)[0])
t("EnumProcessByWMI", lambda: len(list(auto.EnumProcessByWMI() or [])))
print("\n-- janelas de topo (depth=1) --")
for c in root.GetChildren()[:40]:
    print("  ", c.ControlTypeName, "|", repr(c.ClassName), "|", repr(c.Name[:40]), "| pid", c.ProcessId, "| hwnd", c.NativeWindowHandle)
